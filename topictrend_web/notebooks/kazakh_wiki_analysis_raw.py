"""# Merge and prepared delta"""

# Rename 'total_views' column to avoid conflict during merge, as 'total_views' is more generic
df_baseline = df_baseline.rename(columns={'total_views': 'pageviews_baseline'})
df_impact = df_impact.rename(columns={'total_views': 'pageviews_impact'})

# Merge on category names
merged = df_baseline.merge(df_impact, on='category_qid', suffixes=('_baseline', '_impact'), how='outer')

# Create a consolidated 'category_name' column, preferring baseline name
merged['category_name'] = merged['category_name_baseline'].fillna(merged['category_name_impact'])

# Fetch missing page views using get_total_page_views_for_category
for index, row in merged.iterrows():
    qid = row['category_qid']
    if pd.isna(row['pageviews_baseline']):
        # Fetch baseline views for this category QID
        baseline_views = get_total_page_views_for_category(client, qid, "kkwiki", "2025-09-01", "2025-09-30")
        merged.loc[index, 'pageviews_baseline'] = baseline_views if baseline_views is not None else 0
    if pd.isna(row['pageviews_impact']):
        # Fetch impact views for this category QID
        impact_views = get_total_page_views_for_category(client,qid, "kkwiki", "2025-08-01", "2025-08-31")
        merged.loc[index, 'pageviews_impact'] = impact_views if impact_views is not None else 0

# Ensure any remaining NaNs (e.g., if get_total_page_views_for_category returned None) are 0
merged['pageviews_baseline'] = merged['pageviews_baseline'].fillna(0)
merged['pageviews_impact'] = merged['pageviews_impact'].fillna(0)

# Calculate percentage change
# Handle division by zero for categories with 0 baseline views
merged['pageview_delta_pct'] = merged.apply(
    lambda row: ((row['pageviews_impact'] - row['pageviews_baseline']) / row['pageviews_baseline'] * 100)
    if row['pageviews_baseline'] != 0 else (100 if row['pageviews_impact'] > 0 else 0),
    axis=1
)

# Sort by impact (most affected first)
merged = merged.sort_values('pageview_delta_pct', ascending=False)

merged_display = merged[['category_qid','category_name', 'pageviews_baseline', 'pageviews_impact', 'pageview_delta_pct']]

