def get_title_by_qid(client, qid, wiki="enwiki"):
    request = topictrend_pb2.TitleByQidRequest(wiki=wiki,qid=qid)
    try:
      response = client.stub.GetTitleByQid(request)
      return response.title
    except grpc.RpcError as e:
        if e.code() == StatusCode.NOT_FOUND:
            # print(f"Warning: Category QID {qid} not found for wiki {wiki}. Returning None.") # Optional: print warning
            return None # Return None if resource not found
        else:
            client._handle_grpc_error(e) # Re-raise for other types of errors


