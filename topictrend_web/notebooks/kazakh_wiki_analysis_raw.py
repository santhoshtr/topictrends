def get_top_categories(wiki, start_date, end_date, limit):
    request = topictrend_pb2.TopCategoriesRequest(
        wiki=wiki,
        start_date=start_date,
        end_date=end_date,
        limit=limit
    )

    try:
        response = client.stub.GetTopCategories(request)
        data = []
        for category in response.categories:
          category_name = get_title_by_qid(client, category.category_qid, wiki=wiki) # Pass wiki_lang
          if category_name is None:
            category_name = f"Q{category.category_qid} (Name Not Found)"
          data.append({
            'category_qid': category.category_qid,
            'category_name': category_name,
            'total_views': category.total_views
          })
        return data
    except grpc.RpcError as e:
        print(f"RPC failed: {e.code()}, {e.details()}")


